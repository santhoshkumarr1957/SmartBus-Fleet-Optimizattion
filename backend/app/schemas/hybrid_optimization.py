"""Schemas for Hybrid Intelligent Fleet Optimization and Resilience System (Phases 1, 2, 5, 6)."""
from datetime import datetime
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, ConfigDict, Field


class OptimizationRunRequest(BaseModel):
    """Parameters to trigger a hybrid CP-SAT mathematical optimization plan."""

    include_weather: bool = Field(
        default=True,
        description="Whether to incorporate weather-adjusted travel times and speed penalties",
    )
    weather_scenario_override: Optional[str] = Field(
        default=None,
        description="Optional weather scenario override (NORMAL, LIGHT_RAIN, HEAVY_RAIN, SEVERE_WEATHER)",
    )
    max_reallocations: Optional[int] = Field(
        default=4,
        description="Maximum number of simultaneous reallocations allowed across the network",
    )


class OptimizationAllocationItem(BaseModel):
    """An individual bus reallocation selected by the hybrid optimization engine."""

    candidate_id: str
    bus_id: int
    bus_number: str
    source_route_id: int
    source_route_number: str
    target_route_id: int
    target_route_number: str
    bus_capacity: int
    current_occupancy: int
    available_seats: int
    transfer_distance_km: float
    nominal_travel_time_min: float
    weather_adjusted_travel_time_min: float
    utility_score: float
    priority: str
    status: str = Field(
        default="PROPOSED",
        description="PROPOSED, APPROVED, EXECUTED, REJECTED",
    )
    explanation: str

    model_config = ConfigDict(from_attributes=True)


class NetworkMetricsSnapshot(BaseModel):
    """Network-wide performance snapshot used for before/after optimization impact comparison."""

    overloaded_routes_count: int = Field(..., description="Count of routes with load factor >= 80%")
    overloaded_route_numbers: List[str] = Field(default_factory=list)
    underutilized_routes_count: int = Field(..., description="Count of routes with load factor < 50%")
    underutilized_route_numbers: List[str] = Field(default_factory=list)
    total_passengers: int
    total_capacity: int
    fleet_load_factor: float
    total_unmet_demand_proxy: int = Field(
        ...,
        description="Sum of estimated passenger demand exceeding 75% capacity on overloaded routes",
    )
    routes_below_minimum_coverage: int = Field(
        ...,
        description="Routes with 0 operational buses (violating minimum service coverage)",
    )
    operational_buses_count: int
    unavailable_buses_count: int


class OptimizationPlanResponse(BaseModel):
    """Comprehensive plan generated by the hybrid CP-SAT mathematical optimization engine."""

    plan_id: str
    created_at: datetime
    status: str = Field(
        default="GENERATED",
        description="GENERATED, APPROVED, EXECUTED, SUPERSEDED, REJECTED",
    )
    solver_engine: str = Field(
        default="Google OR-Tools CP-SAT (Constraint Programming & Integer Optimization)"
    )
    solver_status: str = Field(
        ...,
        description="OPTIMAL, FEASIBLE, INFEASIBLE, or NO_IMBALANCE",
    )
    objective_value: Optional[float] = Field(
        default=None,
        description="Total net objective utility score evaluated by solver",
    )
    solver_time_ms: float = Field(
        default=0.0,
        description="Execution wall time of the CP-SAT solver in milliseconds",
    )

    # Weather context
    weather_condition: str
    weather_delay_factor: float
    weather_summary: str

    # Allocations
    allocations: List[OptimizationAllocationItem]
    total_allocations_count: int

    # Before and After Impact Analysis (Phase 6)
    baseline_metrics: NetworkMetricsSnapshot
    predicted_metrics: NetworkMetricsSnapshot
    predicted_improvement_pct: float
    total_transfer_distance_km: float
    total_transfer_time_min: float
    capacity_reallocated_seats: int
    binding_constraints: List[str]
    summary_notes: str

    is_advisory: bool = True
    advisory_disclaimer: str = (
        "Mathematical optimization plan is strictly decision-support advisory. "
        "Requires explicit dispatcher review and authorization before real-world fleet execution."
    )

    model_config = ConfigDict(from_attributes=True)


class ScenarioEvaluationRequest(BaseModel):
    """Parameters for evaluating an isolated 'what-if' resilience scenario (Phase 5)."""

    scenario_name: str = Field(default="Resilience Drill", description="Name of scenario")
    demand_overrides: Optional[Dict[str, str]] = Field(
        default=None,
        description="Route demand profile overrides (e.g. {'101': 'HIGH', '202': 'LOW'})",
    )
    simulated_breakdowns: Optional[List[str]] = Field(
        default=None,
        description="List of bus numbers to simulate as broken down (e.g. ['101A', '404B'])",
    )
    weather_scenario: Optional[str] = Field(
        default="NORMAL",
        description="NORMAL, LIGHT_RAIN, HEAVY_RAIN, or SEVERE_WEATHER",
    )
    notes: Optional[str] = None


class ScenarioEvaluationResponse(BaseModel):
    """Result of an isolated resilience scenario simulation."""

    scenario_id: str
    scenario_name: str
    evaluated_at: datetime
    is_simulation: bool = True
    demand_profiles: Dict[str, str]
    broken_down_buses: List[str]
    weather_scenario: str
    weather_speed_factor: float
    weather_impact_description: str
    baseline_metrics: NetworkMetricsSnapshot
    scenario_metrics: NetworkMetricsSnapshot
    resilience_score: float
    resilience_rating: str
    recommended_plan: Optional[OptimizationPlanResponse] = None
    key_findings: List[str]
